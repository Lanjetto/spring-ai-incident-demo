def main():
    rows = []
    per_cat = 300 // len(CATEGORIES)
    extra = 300 % len(CATEGORIES)
    for idx, cat in enumerate(CATEGORIES):
        title, symptoms, resolutions = cat
        count = per_cat + (1 if idx < extra else 0)
        for j in range(count):
            rows.append((
                f"{title}",
                symptoms[j % len(symptoms)],
                resolutions[j % len(resolutions)],
            ))
    random.shuffle(rows)

    lines = ["databaseChangeLog:", "  - changeSet:", "      id: 2", "      author: incident-buckets", "      changes:"]
    for i, (title, symptom, resolution) in enumerate(rows, start=1):
        lines += [
            "        - insert:",
            "            tableName: knowledge_doc",
            "            columns:",
            "              - column:",
            f"                  name: title",
            f"                  value: \"{title}\"",
            "              - column:",
            "                  name: symptom",
            f"                  value: \"{symptom}\"",
            "              - column:",
            "                  name: resolution",
            f"                  value: \"{resolution}\"",
        ]
    content = "\n".join(lines) + "\n"
    with open("src/main/resources/db/changelog/002-seed-knowledge.yaml", "w", encoding="utf-8") as f:
        f.write(content)
    print(f"Wrote {len(rows)} inserts")

if __name__ == "__main__":
    main()
